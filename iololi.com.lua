-- ============================================================================
-- File: iololi.com.lua
-- Zone: iololi.com
-- 用途: LuaDNS(主 DNS) 的 Lua zone 文件 —— 通过 git 集成部署
--       并向 HE.net (dns.he.net) 免费 DNS 开放 AXFR, 让其作为从 DNS
--
-- 部署: 仓库根目录放本文件 → git push → LuaDNS 构建系统自动校验并发布
--       构建结果会以邮件通知; 构建失败先看邮件里的报错行
--
-- 说明:
--   * _a 是系统变量, 编译时自动替换为 zone 名 "iololi.com"
--   * SOA / ns1-ns5.luadns.net 的 NS 记录由 LuaDNS 自动维护, 不要手写
--   * slave() 对第三方从服务器只自动添加 NS 记录, 并同时:
--       1) 把该 IP 加入本 zone 的 AXFR 授权列表(ACL)
--       2) zone 变更时向该 IP 发送 NOTIFY
-- ============================================================================

-- ---- A 记录 ---------------------------------------------------------------
a(_a, "45.55.126.223")                 -- @    A    主站 IPv4

-- ---- CNAME ----------------------------------------------------------------
cname("www", "f2deb537.cdn1cdn1.com.") -- www  CNAME  CDN 接入别名
                                       -- ※ 以阿里云面板上的实际 CDN 值为准,
                                       --   若 CDN 已换, 改成新值即可

-- ---- 邮件(腾讯企业邮) ------------------------------------------------------
mx(_a, "mxbiz1.qq.com.", 5)            -- @    MX   5  mxbiz1.qq.com.
mx(_a, "mxbiz2.qq.com.", 10)           -- @    MX   10 mxbiz2.qq.com.
txt(_a, "v=spf1 include:spf.mail.qq.com ~all")   -- @ TXT SPF

-- 如有 DKIM / DMARC / 域名验证 TXT, 在此追加, 例如:
-- txt("default._domainkey", "v=DKIM1; k=rsa; p=MIIB...")
-- txt("_dmarc", "v=DMARC1; p=none")

-- ============================================================================
-- HE.net 从 DNS 声明(dns.he.net 免费服务, 5 台地理分布服务器)
-- IP 必须与 nsX.he.net 的真实 A 记录一致(2026-10 实测):
--   ns1.he.net = 216.218.130.2
--   ns2.he.net = 216.218.131.2
--   ns3.he.net = 216.218.132.2
--   ns4.he.net = 216.66.1.2
--   ns5.he.net = 216.66.80.18
-- ============================================================================
slave("ns1.he.net", "216.218.130.2")
slave("ns2.he.net", "216.218.131.2")
slave("ns3.he.net", "216.218.132.2")
slave("ns4.he.net", "216.66.1.2")
slave("ns5.he.net", "216.66.80.18")

